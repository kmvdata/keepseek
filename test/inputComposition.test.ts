test('input feature fragments compose deterministically and exactly once', () => {
  for (const fragments of [INPUT_SCRIPT_FRAGMENTS, INPUT_STYLE_FRAGMENTS, INPUT_TEMPLATE_FRAGMENTS]) {
    assert.equal(new Set(fragments).size, fragments.length);
    assert.equal(new Set(fragments.map((fragment) => fragment.id)).size, fragments.length);
    assert.ok(fragments.every((fragment) => fragment.id.length > 0 && fragment.source.length > 0));
    assert.equal(composeWebviewFragments(fragments), fragments.map((fragment) => fragment.source).join(''));
    assert.equal(composeWebviewFragments(fragments), composeWebviewFragments(fragments));
  }

  const duplicate: WebviewFragment = { id: 'duplicate', source: 'a' };
  assert.throws(
    () => composeWebviewFragments([duplicate, { id: 'duplicate', source: 'b' }]),
    /Duplicate or empty Webview fragment id/u
  );
});

test('modular input assembly preserves the reviewed generated bytes', () => {
  assert.equal(hash(getInputScript()), '54180b0b55f3d1eb98ea09641a211b18573e78979251248b345ee6c16c196dda');
  assert.equal(hash(getInputStyles()), '45e840f62cfb972866ee0f6ef28a3d73b556e24dc789f0baafa8280dc49435ff');
  assert.equal(hash(getInputTemplate()), '1aeaf27a964cdd0718e8d2603ad4ce3c247f1d0579bab4a85cb7b93885f041ac');
});

test('assembled input keeps unique DOM ids, public controls, payload fields, and feature CSS', () => {
  const template = getInputTemplate();
  const ids = [...template.matchAll(/\sid="([^"]+)"/gu)].map((match) => match[1]);
  assert.equal(new Set(ids).size, ids.length);
  assert.ok(template.indexOf('id="commandMenuButton"') < template.indexOf('id="goalButton"'));
  assert.match(template, /id="goalButton"[\s\S]*aria-haspopup="dialog"[\s\S]*id="goalHoverCard"/u);
  assert.match(template, /id="goalCreatePane"[\s\S]*id="goalManagePane"/u);
  assert.match(template, /id="goalSelectAll"[\s\S]*id="goalSelectNone"[\s\S]*id="goalProposalWorkItems"/u);
  assert.match(template, /id="goalToggleDebug"/u);
  assert.match(template, /id="goalDraftGenerationStatus"[\s\S]*id="goalGeneratedCriteria"[\s\S]*class="goal-advanced"/u);
  for (const key of [
    'goalCriterionWorkspaceState', 'goalCriterionValidation', 'goalCriterionArtifact', 'goalCriterionManual'
  ]) {
    assert.match(template, new RegExp(`data-i18n="${key}"`, 'u'));
  }
  assert.doesNotMatch(template, /id="goalRegion"/u);

  const script = getInputScript();
  const publicApiStart = script.indexOf('window.keepseekInputControls = {');
  const publicApiEnd = script.indexOf('};', publicApiStart);
  assert.ok(publicApiStart >= 0 && publicApiEnd > publicApiStart);
  const publicApi = script.slice(publicApiStart, publicApiEnd);
  for (const method of [
    'render',
    'renderUsage',
    'showSettingsDialog',
    'showHistorySettingsDialog',
    'showAboutDialog',
    'onSkillDraftCreated',
    'showStatus',
    'isPromptSubmittableEmpty',
    'clearPrompt'
  ]) {
    assert.match(publicApi, new RegExp(`\\b${method}:`, 'u'));
  }

  const submitStart = script.indexOf("composer.addEventListener('submit'");
  const submitEnd = script.indexOf("sendButton.addEventListener('click'", submitStart);
  const submit = script.slice(submitStart, submitEnd);
  for (const field of ['prompt', 'sourceId', 'modelId', 'settings', 'references', 'skillIds']) {
    assert.match(submit, new RegExp(`\\b${field}:`, 'u'));
  }
  assert.match(submit, /type: 'sendPrompt'/u);

  for (const messageType of [
    'openGoalDialog', 'generateGoalDraft', 'cancelGoalDraftGeneration', 'discardGoalProposal',
    'adoptGoalProposal', 'openGoalTrace', 'goalPause', 'goalResume', 'goalStop', 'goalClear',
    'goalAmend', 'goalConfirmCriterion'
  ]) {
    assert.match(script, new RegExp(`type: '${messageType}'`, 'u'));
  }
  assert.match(script, /function renderGoalControls\(\)/u);
  assert.match(script, /function showGoalManager\(\)/u);
  assert.match(script, /adoptFromState: function\(\)/u);
  assert.match(script, /goalToggleDebug/u);
  assert.match(script, /goalResume\.disabled = state\.isBusy \|\| goalActionFeedback\?\.status === 'pending'/u);

  const styles = getInputStyles();
  for (const selector of [
    '.composer-input-inner',
    '.rich-file-link',
    '.reference-menu',
    '.skills-bar',
    '.command-menu',
    '.command-model-option',
    '.composer-goal-btn',
    '.goal-hover-card',
    '.goal-generation-status',
    '.goal-proposal-toolbar',
    '.goal-proposal-work-item',
    '.goal-generated-criterion',
    '.goal-advanced',
    '.goal-manage-pane',
    '.context-progress',
    '.usage-details-dialog',
    '.settings-overlay',
    '.settings-account-workspace',
    '.about-details',
    '.new-account-provider-menu'
  ]) {
    assert.ok(styles.includes(selector), `missing ${selector}`);
  }

  assert.doesNotThrow(() => new Function(script));
  assert.doesNotThrow(() => new Function(getScript()));
});

function hash(value: string): string {
  return createHash('sha256').update(value).digest('hex');
}
