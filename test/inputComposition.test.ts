test('assembled input keeps unique DOM ids, public controls, payload fields, and feature CSS', () => {
  const template = getInputTemplate();
  const ids = [...template.matchAll(/\sid="([^"]+)"/gu)].map((match) => match[1]);
  assert.equal(new Set(ids).size, ids.length);
  assert.doesNotMatch(template, /id="goalButton"|id="goalHoverCard"/u);
  assert.match(template, /id="commandGoalMode"[\s\S]*role="menuitemcheckbox"[\s\S]*aria-checked="false"/u);
  assert.ok(template.lastIndexOf('id="commandGoalMode"') > template.lastIndexOf('id="commandEffortSlider"'));
  assert.match(template, /id="goalCreatePane"/u);
  assert.doesNotMatch(template, /id="goalManagePane"/u);
  assert.match(template, /id="goalSelectAll"[\s\S]*id="goalSelectNone"[\s\S]*id="goalProposalWorkItems"/u);
  assert.doesNotMatch(template, /id="goalToggleDebug"/u);
  assert.match(template, /id="goalDraftGenerationStatus"[\s\S]*id="goalGeneratedCriteria"[\s\S]*class="goal-advanced"/u);
  for (const key of [
    'goalCriterionWorkspaceState', 'goalCriterionValidation', 'goalCriterionArtifact', 'goalCriterionManual'
  ]) {
    assert.match(template, new RegExp(`data-i18n="${key}"`, 'u'));
  }
  assert.doesNotMatch(template, /id="goalRegion"/u);

  const script = getInputScript();
  const publicApiStart = script.indexOf('window.keepseekInputControls = {');
  const publicApiEnd = script.indexOf('};', publicApiStart);
  assert.ok(publicApiStart >= 0 && publicApiEnd > publicApiStart);
  const publicApi = script.slice(publicApiStart, publicApiEnd);
  for (const method of [
    'render',
    'renderUsage',
    'showSettingsDialog',
    'showHistorySettingsDialog',
    'showAboutDialog',
    'onSkillDraftCreated',
    'showStatus',
    'isPromptSubmittableEmpty',
    'clearPrompt'
  ]) {
    assert.match(publicApi, new RegExp(`\\b${method}:`, 'u'));
  }

  const submitStart = script.indexOf("composer.addEventListener('submit'");
  const submitEnd = script.indexOf("sendButton.addEventListener('click'", submitStart);
  const submit = script.slice(submitStart, submitEnd);
  for (const field of ['prompt', 'sourceId', 'modelId', 'settings', 'references', 'skillIds']) {
    assert.match(submit, new RegExp(`\\b${field}:`, 'u'));
  }
  assert.match(submit, /type: 'sendPrompt'/u);
  assert.match(submit, /type: 'prepareGoal'/u);
  assert.match(submit, /goalMode === 'goal_armed'/u);
  assert.match(submit, /state\.goalProposal = \{[\s\S]*?preparationStage: 'validating_input'[\s\S]*?refreshGoalTranscriptCard\(\)/u);

  for (const messageType of [
    'generateGoalDraft', 'cancelGoalDraftGeneration',
    'adoptGoalProposal', 'adoptGoalOriginal',
  ]) {
    assert.match(script, new RegExp(`type: '${messageType}'`, 'u'));
  }
  const fullScript = getScript();
  for (const messageType of [
    'setGoalComposerMode', 'discardGoalProposal', 'openGoalTrace', 'goalPause', 'goalResume', 'goalStop', 'goalClear',
    'goalAmend', 'goalConfirmCriterion'
  ]) {
    assert.match(fullScript, new RegExp(`type: '${messageType}'`, 'u'));
  }
  assert.doesNotMatch(script, /function showGoalManager\(\)/u);
  assert.match(script, /openProposalFromState: openGoalProposalFromState/u);
  assert.match(fullScript, /goalCardFeedback\?\.status === 'pending'/u);

  const styles = getInputStyles();
  for (const selector of [
    '.composer-input-inner',
    '.rich-file-link',
    '.reference-menu',
    '.skills-bar',
    '.command-menu',
    '.command-model-option',
    '.composer.is-goal-mode',
    '.goal-generation-status',
    '.goal-proposal-toolbar',
    '.goal-proposal-work-item',
    '.goal-generated-criterion',
    '.goal-advanced',
    '.context-progress',
    '.usage-details-dialog',
    '.settings-overlay',
    '.settings-account-workspace',
    '.about-details',
    '.new-account-provider-menu'
  ]) {
    assert.ok(styles.includes(selector), `missing ${selector}`);
  }

  assert.doesNotThrow(() => new Function(script));
  assert.doesNotThrow(() => new Function(getScript()));
});

test('Goal menu, composer, confirmation card, and progress card share the host goalUi projection', () => {
  const script = getScript();
  assert.match(script, /var mode = String\(state\.goalUi\?\.mode \|\| 'chat'\)/u);
  assert.match(script, /mode === 'goal_active' \|\| mode === 'goal_terminal' \|\| mode === 'proposal_review'[\s\S]*?focusCard/u);
  assert.match(script, /mode === 'workspace_goal_elsewhere'[\s\S]*?type: 'selectSession'/u);
  assert.match(script, /type: 'setGoalComposerMode', enabled: mode === 'chat'/u);
  assert.match(script, /goalMode !== 'chat' && goalMode !== 'goal_armed'[\s\S]*?focusCard/u);
  assert.match(script, /goalMode === 'goal_armed'[\s\S]*?type: 'prepareGoal'[\s\S]*?else \{[\s\S]*?type: 'sendPrompt'/u);
  assert.match(script, /promptInput\.setAttribute\('contenteditable', editable \? 'true' : 'false'\)/u);
  assert.match(script, /if \(mode === 'proposal_generating' \|\| mode === 'proposal_review'\)[\s\S]*?createGoalProposalTranscriptCard/u);
  assert.doesNotMatch(script, /if \(!proposal\) return null/u);
  assert.match(script, /appendGoalPreparationSkeleton\(card\)/u);
  assert.match(script, /type: 'cancelGoalDraftGeneration'/u);
  assert.match(script, /mode === 'goal_active' \|\| mode === 'goal_terminal'[\s\S]*?createGoalTranscriptCard/u);
  assert.match(script, /if \(goal\.canClear\)[\s\S]*?type: 'goalClear'/u);
  assert.match(script, /if \(!goal\.canClear\)[\s\S]*?type: 'goalAmend'/u);
  assert.match(script, /function selectWithDependencies\(itemId\)[\s\S]*?selectWithDependencies\(String\(dependency\)\)/u);
  assert.match(script, /function unselectWithDependents\(itemId\)[\s\S]*?unselectWithDependents\(String\(item\.id \|\| ''\)\)/u);
  assert.match(script, /goalAvailableValidations\.includes\(entry\[1\]\)/u);
  assert.doesNotMatch(script, /window\.(?:alert|confirm|prompt)\s*\(/u);
});

function hash(value: string): string {
  return createHash('sha256').update(value).digest('hex');
}
